"""Generate exact built-in HDR group capabilities; unknown/custom IDs stay unknown."""
from pathlib import Path
import argparse
import json
import re

repo = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
catalog = json.loads((repo / 'src/Magpie/EffectCatalog/zh-Hans.json').read_text(encoding='utf-8-sig'))
# Direct routes are backed by Bicubic's linear shader or the named native HDR
# backend/SDK contracts. FP16 alone is never evidence for this classification.
direct = {'Bicubic', 'DLSS\\DLSS_SR', 'FSR2\\FSR2_SR', 'FSR3\\FSR3_SR',
          'FSR4\\FSR4_SR', 'XeSS\\XeSS_SR', 'NIS\\NIS'}
fg = {'DLSSFG\\DLSS_FrameGeneration', 'XeSSFG\\XeSS_FrameGeneration'}
converters = {'Color\\HDR_to_SDR', 'Color\\SDR_to_HDR', 'RTXVideo\\RTXVideo_HDR'}
native = direct - {'Bicubic'} | {'DLSSNR\\DLSSNR_AI_Filter', 'RTXVideo\\RTXVideo_VSR', 'RTXVideo\\RTXVideo_Denoise'}
records = []
for effect in sorted(catalog['effects'], key=lambda item: item['id']):
    name = effect['id']
    if name in converters:
        continue
    path = repo / 'src/Effects' / (name.replace('\\', '/') + '.hlsl')
    assert path.is_file(), f'Missing source declaration: {name}'
    shader = path.read_text(encoding='utf-8-sig')
    temporal = bool(re.search(r'//!USE[^\n]*\bDYNAMIC\b', shader)) or name in native or name == 'FrameRate_Filter'
    spatial = False
    for block in shader.split('//!TEXTURE')[1:]:
        if re.search(r'\bTexture2D\s+OUTPUT\b', block):
            for axis in ('WIDTH', 'HEIGHT'):
                match = re.search(rf'//!{axis}\s+([^\n]+)', block)
                if match and match[1].strip() != 'INPUT_' + axis:
                    spatial = True
    kind = 'FrameGeneration' if name in fg else 'DirectHdr' if name in direct else 'RequiresSdr'
    # Other built-ins are registered only for their declared SDR processing
    # contract. This does not claim their algorithms support native HDR.
    records.append(f'\t{{ {json.dumps(name)}, HdrEffectCapability::{kind}, {str(temporal).lower()}, {str(spatial).lower()}, {str(name in native).lower()} }},')
header = '''#pragma once
// Generated by scripts/Generate-HdrEffectCapabilities.py. Do not infer native
// HDR support from texture storage or inheritance of the preceding domain.
#include <array>
#include <string>
#include <string_view>
#include <algorithm>

namespace Magpie {
enum class HdrEffectCapability { Unknown, RequiresSdr, DirectHdr, FrameGeneration };
struct HdrEffectCapabilityRecord {
    std::string_view name;
    HdrEffectCapability capability = HdrEffectCapability::Unknown;
    bool temporal = false;
    bool spatial = false;
    bool nativeBackend = false;
    bool IsBarrier() const noexcept { return temporal || spatial || nativeBackend; }
};
inline constexpr HdrEffectCapabilityRecord HDR_EFFECT_CAPABILITIES[] = {
''' + '\n'.join(records) + '''
};
inline std::string HdrEffectAsciiName(std::string_view name) { return std::string(name); }
inline std::string HdrEffectAsciiName(std::wstring_view name) {
    std::string result;
    for (const auto c : name) { if (c > 127) return {}; result.push_back(char(c)); }
    return result;
}
inline HdrEffectCapabilityRecord GetHdrEffectCapability(std::string_view name) noexcept {
    const auto it = std::ranges::find(HDR_EFFECT_CAPABILITIES, name, &HdrEffectCapabilityRecord::name);
    return it == std::end(HDR_EFFECT_CAPABILITIES) ? HdrEffectCapabilityRecord{} : *it;
}
inline HdrEffectCapabilityRecord GetHdrEffectCapability(std::wstring_view name) {
    return GetHdrEffectCapability(HdrEffectAsciiName(name));
}
}
'''
target = repo / 'src/Magpie.Core/include/HdrEffectCapabilities.h'
if args.check:
    assert target.read_text(encoding='utf-8-sig') == header, 'HDR capabilities are stale; regenerate the header'
else:
    target.write_text(header, encoding='utf-8')
print(f'PASS: {len(records)} exact built-in IDs; unknown/custom IDs remain unknown')
